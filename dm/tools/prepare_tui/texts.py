def T(key, *args):
    """The text of key with its arguments"""
    return TEXTS[key].format(*args)


def plural(n, one, other):
    """The text of one (n == 1) or other with n (English: two forms; another language would choose by its own rules)"""
    return T(one if n == 1 else other, n)
